import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createDeck, addSlide, serializeDeck, validateDeck } from '../deck.js';
import { createSlidesClipboard, encodeSlides } from '../clipboard.js';
import { attachOriginalPPTX, unchangedOriginalPPTX } from '../pptx-source.js';
import { exportPPTX } from '../pptx.js';

const bytesOf = async deck => Buffer.from(await (await exportPPTX(deck)).arrayBuffer());
const png = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl2nWQAAAAASUVORK5CYII=';
const alternatePNG = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAIAAACQd1PeAAAADElEQVR4nGP4z8AAAAMBAQDJ/pLvAAAAAElFTkSuQmCC';
async function fixture() {
  const deck = createDeck();
  const slide = deck.slides[0];
  slide.items = [{ id: 'title', type: 'text', text: 'original title', x: 10, y: 20, width: 400, height: 100 }];
  deck.assets = [{ id: 'logo', name: 'logo.png', mime: 'image/png', dataUrl: 'data:image/png;base64,' + png, width: 1, height: 1, fingerprint: 'same declared fingerprint' }];
  addSlide(deck).items.push({ id: 'logo-frame', type: 'image', assetId: 'logo', x: 20, y: 20, width: 100, height: 100 });
  // A ZIP archive comment is an example of source bytes not regenerated by this editor.
  const raw = await bytesOf(deck);
  const comment = Buffer.from('Only the original archive contains this comment.');
  raw.writeUInt16LE(comment.length, raw.length - 2);
  const original = Buffer.concat([raw, comment]);
  const attachment = { name: 'poster.pptx', data: original.toString('base64'), sha256: createHash('sha256').update(original).digest('hex') };
  await attachOriginalPPTX(deck, attachment);
  return { deck, original, attachment };
}

test('reopened complete import exports the exact Office package, including after changing active page', async () => {
  const { deck, original, attachment } = await fixture();
  const reopened = validateDeck(JSON.parse(serializeDeck(deck)));
  reopened.activeSlideId = reopened.slides[0].id;
  const archive = await unchangedOriginalPPTX(reopened);
  assert.equal(archive.data, attachment.data);
  assert.equal(archive.sha256, attachment.sha256);
  assert.deepEqual(await bytesOf(reopened), original);
  assert.equal(createSlidesClipboard(reopened, new Set(reopened.slides.map(s => s.id))).originalPptx, undefined);
  assert.ok(!encodeSlides(reopened).includes('originalPptx'));
});

test('live text, geometry, slide order and asset changes bypass the archived PPTX', async () => {
  const { deck, original } = await fixture();
  for (const edit of [
    d => { d.slides[0].items[0].text = 'edited title'; },
    d => { d.slides[0].items[0].y += 10; },
    d => { d.slides.reverse(); },
    d => { d.slides[1].items[0].hidden = true; },
    d => { d.assets[0].dataUrl = 'data:image/png;base64,' + alternatePNG; },
  ]) {
    const edited = validateDeck(deck);
    edit(edited);
    assert.equal(await unchangedOriginalPPTX(edited), null);
    const bytes = await bytesOf(edited);
    assert.notDeepEqual(bytes, original);
    if (edited.slides[0].items[0].text === 'edited title') assert.ok(bytes.includes('edited title'));
  }
});

test('wrong source digest, partial imports and damaged stored sources cannot be exported as original', async () => {
  const { deck, attachment } = await fixture();
  await assert.rejects(attachOriginalPPTX(deck, { ...attachment, sha256: '1'.repeat(64) }), /differs/);
  const partial = validateDeck(deck); partial.slides.pop(); partial.activeSlideId = partial.slides[0].id;
  await assert.rejects(attachOriginalPPTX(partial, attachment), /page count/);
  const json = JSON.parse(serializeDeck(deck));
  json.originalPptx.sha256 = '1'.repeat(64);
  await assert.rejects(exportPPTX(json), /differs/);
});
